/**
 * The words a chapter contains, according to the implementation that has been
 * showing them for weeks.
 *
 * 2.x lays most works out as native text rather than handing them to a
 * WebView. The risk in that is not that it looks different — it is that it
 * quietly loses something: a paragraph inside a div nobody expected, the
 * contents of a tag the new renderer has no case for.
 *
 * So the words are written down here, from the real saved work page, and the
 * Dart document model must produce the same ones in the same order. Layout can
 * differ between the two readers. The text cannot.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { parseWorkPage } from '../app/core/ao3/parse.js';
import { htmlToText } from '../app/core/epub.js';

const page = readFileSync(new URL('../test/fixtures/work-page.html', import.meta.url), 'utf8');
const work = parseWorkPage(page);

/* A handful of shapes that fic actually uses, alongside the real chapters:
   the awkward ones are where a renderer drops something. */
const SHAPES = [
  '<p>Plain.</p>',
  '<div><div><p>Buried two deep.</p></div></div>',
  '<p>Before</p><blockquote><p>Quoted</p></blockquote><p>After</p>',
  '<p>A line<br>and another</p>',
  '<ul><li>One</li><li>Two</li></ul>',
  '<p align="center">Centred.</p>',
  '<p>An <em>emphasis</em> inside <strong>a sentence</strong>.</p>',
  '<p>Text before a rule</p><hr><p>and after</p>',
  '<p>Unclosed<p>paragraphs<em>and marks</p>',
  '<center>Bare text in a centre tag</center>',
  '<p>Trailing whitespace   </p>',
  '<p>&amp; entities &mdash; and &#8212; numeric</p>',
];

const words = (text) => String(text).split(/\s+/).filter(Boolean);

const out = {
  note: 'Generated by tools/emit-chapter-conformance.mjs. The Dart document '
      + 'model must produce these words, in this order, from this markup.',
  chapters: (work.chapters ?? []).slice(0, 3).map((ch, i) => ({
    number: i + 1,
    html: ch.html,
    words: words(htmlToText(ch.html)),
  })),
  shapes: SHAPES.map((html) => ({ html, words: words(htmlToText(html)) })),
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/chapters.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(
  `wrote ${out.chapters.length} real chapters and ${out.shapes.length} shapes\n`);
