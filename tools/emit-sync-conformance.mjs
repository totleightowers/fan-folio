/**
 * What 1.x decides about a failure, written down for 2.x to be held to.
 *
 * isTransient is a stack of regular expressions with an order that matters: a
 * 429 has to be read as "slow down" before the blanket 4xx rule reads it as
 * "no". Getting that wrong during a long download is the worst possible
 * failure — the moment the archive starts throttling, every work in flight is
 * permanently written off as unavailable — and it is exactly the sort of thing
 * a port gets subtly wrong without anybody noticing.
 */
import { writeFileSync } from 'node:fs';
import { isTransient, retryDelay, listingCost, shouldWalkWholeListing, PER_LISTING_PAGE }
  from '../app/core/sync/run.js';

const REASONS = [
  'the archive answered 429',
  'the archive answered 408',
  'the archive answered 425',
  'the archive answered 403',
  'the archive answered 404',
  'the archive answered 401',
  'the archive answered 451',
  'the archive answered 500',
  'the archive answered 502',
  'the archive answered 503',
  'rate limit exceeded',
  'Too Many Requests',
  'retry-after: 60',
  'retry after a while',
  'the server asked us to slow down',
  'this work was deleted',
  'that work does not exist',
  'no chapters found',
  'could not reach the archive',
  'the request timed out',
  'Timeout while connecting',
  'network is unreachable',
  'failed to fetch',
  'unable to resolve host "archiveofourown.org"',
  'No address associated with hostname',
  'java.net.UnknownHostException',
  'ENOTFOUND archiveofourown.org',
  'EAI_AGAIN',
  'connection reset by peer',
  'Connection refused',
  'connection abort',
  'connection closed',
  'ECONNRESET',
  'ECONNREFUSED',
  'ECONNABORTED',
  'unexpected end of stream',
  'broken pipe',
  'Software caused connection abort',
  'javax.net.ssl.SSLException: handshake failed',
  'SSL handshake aborted',
  'java.net.SocketException',
  'java.net.SocketTimeoutException',
  'protocol error',
  /* And the ones that should be read as a plain no. A work that is gone is
     gone, and asking again is rude and pointless. */
  'something went wrong',
  'the page had no work on it',
  '',
  null,
  undefined,
  /* The one that caught 1.x out: a 429 mentioned alongside a 4xx phrase. The
     order of the rules is the whole answer here. */
  'the archive answered 429 after the archive answered 403 earlier',
];

const out = {
  note: 'Generated by tools/emit-sync-conformance.mjs from the 1.x '
      + 'implementation. The Dart port is held to these answers.',
  perListingPage: PER_LISTING_PAGE,
  failures: REASONS.map((reason) => ({
    reason: reason ?? null,
    transient: isTransient(reason),
  })),
  retries: [0, 1, 2, 3, 4, 5, 9].map((attempt) => ({
    attempt,
    ms: retryDelay(attempt),
  })),
  listings: [null, 0, 1, 2, 9, 10, 11, 86, 200].map((pages) => ({
    pages,
    cost: listingCost(pages),
    whole: shouldWalkWholeListing(pages),
  })),
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/sync.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(
  `wrote ${out.failures.length} failures and ${out.listings.length} listings\n`);
