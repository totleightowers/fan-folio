/**
 * What 1.x does when a work or an author is let go of, written down.
 *
 * A delete is a list and an order; a block is a rule about collaborations.
 * Three implementations now run them — the shell in Java, the dev server in
 * JavaScript, and the Flutter app in Dart — and none can import another's
 * code. The JS is the one that has been in front of a real archive, so this
 * records what it says and the Dart tests are held to it.
 *
 * When a rule legitimately changes, this is regenerated and the diff shows
 * exactly which answers moved.
 */
import { writeFileSync } from 'node:fs';
import { INDEX_FIRST, WORK_OWNS, deleteStatements, TOMBSTONE }
  from '../app/core/store/delete.js';
import { authorsOf, isHidden, worksByPattern } from '../app/core/store/blocked.js';

/* The shapes an authors column actually arrives in. The last few are the ones
   worth having a fixture for: a column written before this app used JSON, a
   name with a quote in it, and an empty list. */
const AUTHORS = [
  '["ann"]',
  '["ann","bee"]',
  '["ann","bee","cee"]',
  '[]',
  '',
  null,
  'ann',
  'not json at all',
  '["Anna"]',
  '["Annabel"]',
  '["ann", "ann"]',
  '["O\'Brien"]',
  '["a \\"quoted\\" name"]',
  '[1, 2]',
  '{"not":"a list"}',
];

/* And the sets of blocked names those are asked about. */
const BLOCKLISTS = [[], ['ann'], ['bee'], ['ann', 'bee'], ['Anna'], ['O\'Brien'], ['1']];

/* Names a blocklist is built from, including the ones that need escaping in
   a LIKE pattern — a name with a percent sign in it is rare and is exactly
   the sort of thing that silently matches the whole library. */
const NAMES = [
  'ann',
  'Anna',
  'Annabel',
  "O'Brien",
  'a "quoted" name',
  '100% Sure',
  'under_score',
  'back\\slash',
  'orphan_account',
  '',
];

const out = {
  note: 'Generated by tools/emit-tidy-conformance.mjs from the 1.x '
      + 'implementation. The Dart port is held to these answers.',
  indexFirst: INDEX_FIRST,
  workOwns: WORK_OWNS,
  deleteStatements: deleteStatements(),
  tombstone: TOMBSTONE,
  authors: AUTHORS.map((raw) => ({
    raw,
    names: authorsOf(raw),
    hidden: BLOCKLISTS.map((blocked) => ({ blocked, hidden: isHidden(raw, blocked) })),
  })),
  patterns: NAMES.map((name) => ({ name, pattern: worksByPattern(name) })),
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/tidy.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(
  `wrote ${out.authors.length} author columns and ${out.patterns.length} patterns\n`);
