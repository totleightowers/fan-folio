/**
 * What 1.x decides to fetch, and what it reads off a form.
 *
 * Both of these are places where being subtly wrong is expensive and quiet. A
 * wrong "skip" leaves a gap in the library nobody notices until they open the
 * work; a form field read wrongly submits a private bookmark as a public one.
 * So the JavaScript answers are written down and the Dart port is held to
 * them, the same arrangement the links and the retry rules have.
 */
import { writeFileSync } from 'node:fs';
import { planSync, epochToDate, heldAsOf, estimate, mergeListings }
  from '../app/core/sync/plan.js';
import { parseForm, csrfToken, encodeForm } from '../app/core/ao3/forms.js';

/* A work is decided by two dates and two flags, so this is every combination
   that changes the answer rather than a handful of plausible ones. */
const LISTED = {
  absent: 1735689600,        // 2025-01-01, and not held at all
  older: 1735689600,         // held copy is newer
  newer: 1767225600,         // 2026-01-01, newer than the held copy
  same: 1735689600,
  undated: null,             // the archive said nothing
  skinless: 1735689600,
  skinned: 1735689600,
  onlyPublished: 1735689600,
};

/* The planner reads an updatedAt off a listing blurb; the Dart port is handed
   the epoch directly, since that is the only field of it this decision uses.
   Same inputs, said the way each side says them. */
const BLURBS = Object.fromEntries(
  Object.entries(LISTED).map(([id, updatedAt]) => [id, { updatedAt }]));

const HELD = {
  older: { downloadedAt: '2026-06-01' },
  newer: { downloadedAt: '2025-06-01' },
  same: { downloadedAt: '2025-01-01' },
  undated: {},
  skinless: { downloadedAt: '2026-06-01', needsSkin: true },
  skinned: { downloadedAt: '2026-06-01', needsSkin: true, skinCss: 'p{}' },
  onlyPublished: { published: '2024-01-01' },
};

const FORMS = [
  {
    name: 'a kudos form, with its token and its hidden fields',
    match: 'kudo',
    html: `<form class="new_kudo" id="new_kudo" action="/kudos" accept-charset="UTF-8" method="post">
      <input name="utf8" type="hidden" value="&#x2713;" />
      <input type="hidden" name="authenticity_token" value="a+b/c=&amp;d" />
      <input type="hidden" name="kudo[commentable_id]" value="58374928" />
      <input type="hidden" name="kudo[commentable_type]" value="Work" />
      <input type="submit" name="commit" value="Kudos" />
    </form>`,
  },
  {
    name: 'a bookmark form, where an unticked box must stay unticked',
    match: 'bookmark',
    html: `<form id="bookmark-form" action="/works/1/bookmarks" method="post">
      <input type="hidden" name="authenticity_token" value="tok" />
      <textarea name="bookmark[bookmarker_notes]">notes with &amp; and &lt;b&gt;</textarea>
      <input type="checkbox" name="bookmark[private]" value="1" />
      <input type="checkbox" name="bookmark[rec]" value="1" checked />
      <select name="bookmark[pseud_id]">
        <option value="1">one</option>
        <option value="2" selected>two</option>
      </select>
      <input type="submit" value="Create" />
    </form>`,
  },
  {
    name: 'a select with nothing selected sends the first option',
    match: 'id="pick"',
    html: `<form id="pick" action="/x"><select name="s">
      <option value="a">A</option><option value="b">B</option></select></form>`,
  },
  {
    name: 'a radio group sends only the checked one',
    match: 'id="radios"',
    html: `<form id="radios" action="/x" method="GET">
      <input type="radio" name="r" value="no">
      <input type="radio" name="r" value="yes" checked>
      <input type="file" name="f">
      <input type="text" name="t" value="kept">
    </form>`,
  },
  {
    name: 'a form that is not on the page',
    match: 'nothing-like-this',
    html: '<p>no forms here</p>',
  },
  {
    name: 'a sign-in form',
    match: 'new_user',
    html: `<form id="new_user" action="/users/login" method="post">
      <input type="hidden" name="authenticity_token" value="sign+in/token=" />
      <input type="text" name="user[login]" value="" />
      <input type="password" name="user[password]" />
      <input type="checkbox" name="user[remember_me]" value="1" checked />
    </form>`,
  },
];

const TOKEN_PAGES = [
  '<meta name="csrf-token" content="from+the/meta=">',
  "<meta name='csrf-token' content='single quoted'>",
  '<input type="hidden" name="authenticity_token" value="from&amp;the&amp;input">',
  '<p>nothing here</p>',
];

const out = {
  note: 'Generated by tools/emit-plan-conformance.mjs from the 1.x '
      + 'implementation. The Dart port is held to these answers.',
  listed: LISTED,
  held: HELD,
  epochs: [null, 0, 1735689600, 1767225600, 1e20].map((e) => ({
    epoch: e, date: epochToDate(e),
  })),
  heldAsOf: Object.entries(HELD).map(([key, held]) => ({
    key, asOf: heldAsOf(held) ?? null,
  })),
  plan: (() => {
    const { actions, reasons, counts } = planSync(BLURBS, HELD);
    return { actions, counts, reasons: Object.fromEntries(reasons) };
  })(),
  planWithoutSkins: (() => {
    const { actions, counts } = planSync(BLURBS, HELD, { wantSkins: false });
    return { actions, counts };
  })(),
  estimates: [0, 1, 20, 124, 8030].map((n) => ({ n, ...estimate(n) })),
  merged: (() => {
    const merged = mergeListings({
      bookmarks: { a: { updatedAt: 100 }, both: { updatedAt: 100 } },
      history: { b: { updatedAt: 200 }, both: { updatedAt: 300 } },
    });
    return Object.fromEntries([...merged].map(([id, w]) => [id, {
      updatedAt: w.updatedAt ?? null,
      inBookmarks: w.inBookmarks ?? false,
      inHistory: w.inHistory ?? false,
    }]));
  })(),
  /* The page goes in the fixture beside the answer. Keeping the input in the
     emitter and a copy of it in the Dart test would be a second place for the
     two to drift, which is the thing this whole arrangement exists to stop. */
  forms: FORMS.map(({ name, html, match }) => {
    const form = parseForm(html, match);
    return { name, match, html, form, body: form ? encodeForm(form.fields) : null };
  }),
  tokens: TOKEN_PAGES.map((html) => ({ html, token: csrfToken(html) ?? null })),
  encoded: [
    { a: 'b' },
    { 'with space': 'and space' },
    { 'kudo[commentable_id]': '58374928' },
    { token: 'a+b/c=' },
    { empty: '' },
    { 'ünïcode': 'réply' },
  ].map((fields) => ({ fields, body: encodeForm(fields) })),
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/plan.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`wrote ${out.forms.length} forms and ${out.estimates.length} estimates\n`);
