/**
 * What 1.x reads out of a page, for 2.x to be held to.
 *
 * A parser is the one place in this app where being subtly wrong is invisible:
 * a work with the wrong tags, a chapter count off by one, an author dropped
 * from a byline — none of that announces itself. It sits in the library
 * looking like data.
 *
 * So the real saved pages are run through the implementation that has been
 * reading the real archive for weeks, and what it extracted is written down.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { parseListing, parseWorkPage } from '../app/core/ao3/parse.js';

const fixture = (name) =>
  readFileSync(new URL(`../test/fixtures/${name}`, import.meta.url), 'utf8');

/* The work page carries the chapters and the skin, which are the two things a
   reader cannot do without. The chapter HTML itself is covered by the chapter
   fixture, so only its shape is recorded here. */
const work = parseWorkPage(fixture('work-page.html'));

const out = {
  note: 'Generated by tools/emit-parse-conformance.mjs from the 1.x parser.',
  listings: ['listing.html', 'bookmarks.html'].map((name) => ({
    fixture: name,
    ...parseListing(fixture(name)),
  })),
  /* The work page keeps its archive metadata under `meta` rather than at the
     top level, which is where a first draft of this looked for it — and
     recorded a row of nulls that the port then had to be wrong to match. */
  work: {
    workId: work.workId,
    title: work.title,
    authors: work.authors,
    summary: work.summary,
    chapterCount: (work.chapters ?? []).length,
    hasSkin: Boolean(work.skinCss),
    meta: {
      words: work.meta?.words ?? null,
      language: work.meta?.language ?? null,
      rating: work.meta?.rating ?? null,
      complete: work.meta?.complete ?? null,
      fandoms: work.meta?.fandoms ?? [],
      relationships: work.meta?.relationships ?? [],
      characters: work.meta?.characters ?? [],
      freeform: work.meta?.freeform ?? [],
      warnings: work.meta?.warnings ?? [],
      categories: work.meta?.categories ?? [],
    },
  },
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/parse.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(
  `wrote ${out.listings.length} listings (${out.listings.reduce((n, l) => n + l.works.length, 0)} works) `
  + `and one work page\n`);
