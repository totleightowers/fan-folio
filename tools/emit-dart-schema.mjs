/**
 * The schema, emitted for Dart from the one place it is written.
 *
 * Two copies of a schema is two schemas, and 2.x opens the database 1.x
 * wrote — so they have to be the same one. The JavaScript module is the
 * source because the 1.x app imports it in a browser, where there is no
 * filesystem to read a .sql file from.
 *
 * The statements are split here rather than in Dart, using the splitter the
 * shell already uses and the tests already cover. Splitting SQL is a small
 * job with one trap in it — the comments contain semicolons of their own —
 * and the way to not fall into it twice is to not write it twice.
 */
import { SCHEMA } from '../app/core/store/schema.js';
import { executable } from './emit-schema-sql.mjs';
import { writeFileSync } from 'node:fs';

const statements = executable(SCHEMA)
  .split(';')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => `${s};`);

const quoted = statements
  .map((s) => `  r"""\n${s}\n""",`)
  .join('\n');

const out = `// GENERATED by tools/emit-dart-schema.mjs — do not edit.
//
// The schema lives in app/core/store/schema.js, which the 1.x app imports in a
// browser where there is no filesystem to read a .sql file from. This is that
// schema, emitted for Dart and already split into statements by the splitter
// the shell uses. A test regenerates it and fails if it has drifted, because
// 2.x opens the database 1.x wrote and they have to be the same schema.

/// Every statement of the schema, in order, ready to run one at a time.
const List<String> schemaStatements = [
${quoted}
];
`;
writeFileSync(new URL('../dart/folio_core/lib/src/store/schema.g.dart', import.meta.url), out);
process.stdout.write(`wrote ${statements.length} statements\n`);
