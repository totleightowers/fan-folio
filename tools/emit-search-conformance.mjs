/**
 * What 1.x scores a search result, written down for 2.x to match.
 *
 * Ranking is the part of search nobody can eyeball: a wrong order looks like
 * a plausible order. So the blobs SQLite actually produces for real queries
 * over the real fixture are recorded here with the scores 1.x gives them, and
 * the Dart port has to agree — not approximately, since two rankers that
 * disagree by a hair still put different works first.
 */
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync } from 'node:fs';
import { SCHEMA } from '../app/core/store/schema.js';
import { executable } from './emit-schema-sql.mjs';
import { parseWorkPage } from '../app/core/ao3/parse.js';
import { htmlToText } from '../app/core/epub.js';
import { bm25 } from '../app/core/search.js';

const db = new DatabaseSync(':memory:');
db.exec(executable(SCHEMA));

const page = readFileSync(new URL('../test/fixtures/work-page.html', import.meta.url), 'utf8');
const work = parseWorkPage(page);

const insert = db.prepare(
  'INSERT INTO chapters (work_id, number, title, text) VALUES (?,?,?,?)');
(work.chapters ?? []).forEach((ch, i) => {
  insert.run('1', i + 1, ch.title ?? null, htmlToText(ch.html));
});
/* Something short, so lengths differ and the normalisation has work to do. */
insert.run('2', 1, 'Short', 'the vessel shimmering');
db.exec("INSERT INTO chapter_fts(chapter_fts) VALUES('rebuild')");

const QUERIES = ['vessel', 'shimmering', 'the', 'vessel shimmering', '"right before"'];

const out = {
  note: 'Generated by tools/emit-search-conformance.mjs. The blobs are what '
      + 'SQLite produced; the scores are what 1.x computed from them.',
  cases: QUERIES.map((q) => {
    const rows = db.prepare(`
      SELECT rowid, matchinfo(chapter_fts, 'pcnalx') AS m
      FROM chapter_fts WHERE chapter_fts MATCH ?`).all(q);
    return {
      query: q,
      rows: rows.map((r) => ({
        rowid: r.rowid,
        matchinfo: Buffer.from(r.m).toString('base64'),
        score: bm25(r.m),
      })),
    };
  }),
};

writeFileSync(
  new URL('../dart/folio_core/test/conformance/search.json', import.meta.url),
  `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`wrote ${out.cases.length} queries, `
  + `${out.cases.reduce((n, c) => n + c.rows.length, 0)} scored rows\n`);
